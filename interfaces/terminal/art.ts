import { readFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const TITLE_PATH = join(__dirname, '../scratch/title.txt');

const loadAegisTitle = (): string[] => {
  try {
    const data = readFileSync(TITLE_PATH, 'utf8');
    const lines = data.split(/\r?\n/);
    if (lines.some(line => line.trim())) {
      return lines;
    }
  } catch (error) {
    // fallback to built-in ASCII title if scratch title isn't available
  }

  return [
    '    AAAAA    EEEEEEE   GGGGGG   IIIII   SSSSSS ',
    '   AA   AA   EE       GG          II    SS      ',
    '  AAAAAAAA   EEEEE    GG  GGG     II     SSSSS ',
    ' AA      AA  EE       GG   GG     II         SS',
    'AA        AA EEEEEEE   GGGGGG   IIIII  SSSSSS ',
  ];
};

